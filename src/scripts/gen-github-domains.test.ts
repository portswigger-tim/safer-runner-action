import * as fs from 'fs';
import { GENERATED_FILE, generatedDomains, renderGeneratedFile } from './gen-github-domains';
import { GITHUB_ACTIONS_DOMAINS } from '../config/github-domains.generated';

describe('gen:domains', () => {
  it('is verbatim: only non-strings and duplicates are dropped (the runtime does the checks)', () => {
    expect(generatedDomains(['github.com', '*.github.com', '*.core.windows.net', 7, 'github.com'])).toEqual([
      'github.com',
      '*.github.com',
      '*.core.windows.net'
    ]);
  });

  it('renders a header that says it is generated, and the array', () => {
    const out = renderGeneratedFile(['a.example.com', '*.b.example.com'], '2026-11-05');
    expect(out).toMatch(/^\/\/ GENERATED by `npm run gen:domains` [^]* on 2026-11-05/);
    expect(out).toContain('export const GITHUB_ACTIONS_DOMAINS: readonly string[] = [\n  "a.example.com",\n');
  });

  it('an entry cannot break out of its string literal', () => {
    const out = renderGeneratedFile(["x.com'];require('child_process');//"], '2026-11-05');
    expect(out).toContain("  \"x.com'];require('child_process');//\"\n];");
  });

  it('the committed snapshot is exactly what the generator would write for its own content', () => {
    const date = /on (\d{4}-\d{2}-\d{2})/.exec(fs.readFileSync(GENERATED_FILE, 'utf8'))![1];
    // prettier turns the generator's double quotes into single ones
    expect(fs.readFileSync(GENERATED_FILE, 'utf8')).toBe(
      renderGeneratedFile(generatedDomains([...GITHUB_ACTIONS_DOMAINS]), date).replace(/"/g, "'")
    );
  });
});
